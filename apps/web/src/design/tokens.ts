/**
 * The design tokens, exported from the one place they are defined (DSN-02, split out of DSN-01).
 *
 * The source is `tailwind.config.ts` (palette, fonts, radii, shadows) and the variables in `src/app/globals.css` (the semantic names: background, card, border…). This reads both and
 * writes them in the W3C Design Tokens format (`$type`, `$value`), so a designer's tool or another app can use exactly what the product uses. Nothing here is typed by hand: change
 * the config, run `npm run tokens`, and the committed `design-tokens.json` follows; a test fails when the two have drifted apart.
 */
import config from '../../tailwind.config';

type Node = { $type: string; $value: string | string[]; $description?: string };
export type TokenGroup = { [key: string]: Node | TokenGroup };

const hslToHex = (triplet: string): string => {
  const m = /^\s*(\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)%\s+(\d+(?:\.\d+)?)%\s*$/.exec(triplet);
  if (!m) return triplet.trim();
  const h = Number(m[1]), s = Number(m[2]) / 100, l = Number(m[3]) / 100;
  const k = (n: number) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n: number) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return '#' + [f(0), f(8), f(4)].map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
};

/** `--name: value;` pairs of the first `:root` block of the stylesheet. */
export function rootVariables(css: string): Record<string, string> {
  const block = /:root\s*\{([^}]*)\}/.exec(css)?.[1] ?? '';
  const out: Record<string, string> = {};
  for (const m of block.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) out[m[1]!] = m[2]!.replace(/\/\*.*?\*\//g, '').trim();
  return out;
}

export function buildTokens(css: string): TokenGroup {
  const ext = (config.theme?.extend ?? {}) as Record<string, any>;
  const vars = rootVariables(css);
  const color: TokenGroup = {};
  for (const [name, value] of Object.entries(ext.colors ?? {})) {
    if (typeof value === 'string') {
      const v = /^hsl\(var\(--([\w-]+)\)\)$/.exec(value);
      color[name] = { $type: 'color', $value: v ? hslToHex(vars[v[1]!] ?? '') : value.toUpperCase(), ...(v ? { $description: `semantic: var(--${v[1]})` } : {}) };
    } else {
      const g: TokenGroup = {};
      for (const [shade, hex] of Object.entries(value as Record<string, string>)) {
        const v = /^hsl\(var\(--([\w-]+)\)\)$/.exec(hex);
        g[shade.toLowerCase()] = { $type: 'color', $value: v ? hslToHex(vars[v[1]!] ?? '') : hex.toUpperCase(), ...(v ? { $description: `semantic: var(--${v[1]})` } : {}) };
      }
      color[name] = g;
    }
  }
  const fontFamily: TokenGroup = {};
  for (const [name, stack] of Object.entries((ext.fontFamily ?? {}) as Record<string, string[]>)) fontFamily[name] = { $type: 'fontFamily', $value: stack.map((s) => s.replace(/^'|'$/g, '')) };
  const shadow: TokenGroup = {};
  for (const [name, v] of Object.entries((ext.boxShadow ?? {}) as Record<string, string>)) shadow[name] = { $type: 'shadow', $value: v };
  return {
    color,
    fontFamily,
    radius: { base: { $type: 'dimension', $value: vars.radius ?? '0.75rem' } },
    shadow,
  };
}

export const serializeTokens = (css: string): string => JSON.stringify({ $description: 'SurveyFlow design tokens. Generated by `npm run tokens` from tailwind.config.ts and src/app/globals.css: do not edit by hand.', ...buildTokens(css) }, null, 2) + '\n';
